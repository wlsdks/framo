import { describe, expect, it } from 'vitest'
import { tokensOf } from './blocks/parts'

describe('여러 값이 든 한 칸 읽기', () => {
  it.each([
    ['10, 확인 중, 20', ['10', '확인 중', '20']],
    ['10,확인 중,20', ['10', '확인 중', '20']],
    ['10, , 20', ['10', '', '20']],
    ['10,,20', ['10', '', '20']],
    ['10, 20,', ['10', '20', '']],
    ['', []],
    ['10 / 확인 중 / 20', ['10', '확인 중', '20']],
    ['10 건, 20 건, 30 건', ['10 건', '20 건', '30 건']],
    ['1,200, 2,500, 3,100', ['1,200', '2,500', '3,100']],
    ['1,200만원, 2,500만원', ['1,200만원', '2,500만원']],
    ['10,20,30', ['10', '20', '30']],
    ['10 20 30', ['10', '20', '30']],
    ['10, -, 20', ['10', '-', '20']],
  ])('칸의 순서와 단위를 지킨다: %s', (text, expected) => {
    expect(tokensOf(text)).toEqual(expected)
  })
})
